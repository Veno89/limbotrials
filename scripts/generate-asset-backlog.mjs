import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createServer } from 'vite';

const outputPath = path.resolve('docs/ASSET_PRODUCTION_BACKLOG.md');
const checkOnly = process.argv.includes('--check');
const tierSections = [
  ['minimum-playable', '1. Minimum playable / demo-critical'],
  ['presentation-polish', '2. Required presentation polish'],
  ['optional-variation', '3. Optional variation'],
  ['post-demo', '4. Post-demo content'],
];

const server = await createServer({ appType: 'custom', server: { middlewareMode: true } });

try {
  const { VISUAL_ASSETS, AUDIO_ASSET_MANIFEST } = await server.ssrLoadModule(
    '/src/game/data/assets.ts',
  );
  const productionAssets = VISUAL_ASSETS
    .filter((asset) => asset.production)
    .sort((left, right) =>
      left.production.order - right.production.order || left.id.localeCompare(right.id),
    );

  const lines = [
    '# Asset Production Backlog',
    '',
    '> Generated by `npm run assets:backlog` from the runtime asset manifest. Edit manifest metadata, then regenerate this file.',
    '',
    'The game remains playable while these files are absent: every listed visual has an owner-created source, a semantic alias, or a bounded Phaser primitive fallback. Replacing art never requires weapon or enemy implementation changes.',
    '',
    `Registered production tasks: **${productionAssets.length} visual** and **${AUDIO_ASSET_MANIFEST.length} audio**.`,
    '',
  ];

  for (const [tier, heading] of tierSections) {
    lines.push(`## ${heading}`, '');
    const entries = productionAssets.filter((asset) => asset.production.tier === tier);
    if (entries.length === 0 && tier !== 'presentation-polish') {
      lines.push('No current-slice runtime dependency is registered in this tier. Keep this work deferred.', '');
    }
    for (const [index, asset] of entries.entries()) {
      lines.push(...renderVisualEntry(asset, index + 1));
    }
    if (tier === 'presentation-polish') {
      lines.push('### Procedural audio replacements', '');
      lines.push('Audio is centralized in the same manifest. These cues are functional Web Audio placeholders; replacement is presentation work, not a gameplay blocker.', '');
      for (const [index, audio] of AUDIO_ASSET_MANIFEST.entries()) {
        lines.push(...renderAudioEntry(audio, index + 1));
      }
    }
  }

  lines.push(
    '## Integration acceptance gate',
    '',
    'For each delivered visual: update only its explicit import/source row in `src/game/data/assets.ts`, run `npm run validate:content`, inspect it in the F11 Content Lab with applicable origin/attachment/collision guides enabled, then run `npm run verify:release` (which creates a fresh production build before both browser smokes). Preserve the stable asset ID.',
    '',
    'For each delivered audio file: add its explicit imported source to the existing manifest cue, validate content, manually confirm the WAV metadata below, then audition it in live menus/gameplay through the master plus music/effects volume controls and run `npm run verify:release`. Audio has no visual Content Lab guide pass, and content validation does not parse WAV headers.',
    '',
  );

  const generated = `${lines.join('\n')}\n`;
  if (checkOnly) {
    const current = await readFile(outputPath, 'utf8').catch(() => undefined);
    if (current !== generated) {
      throw new Error(
        `${path.relative(process.cwd(), outputPath)} is missing or stale. Run npm run assets:backlog.`,
      );
    }
    console.log(
      `${path.relative(process.cwd(), outputPath)} matches the manifest (${productionAssets.length} visual tasks).`,
    );
  } else {
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, generated, 'utf8');
    console.log(
      `Wrote ${path.relative(process.cwd(), outputPath)} (${productionAssets.length} visual tasks).`,
    );
  }
} finally {
  await server.close();
}

function renderVisualEntry(asset, ordinal) {
  const production = asset.production;
  const collision = asset.collision
    ? asset.collision.shape === 'circle'
      ? `circle radius ${asset.collision.radius}px`
      : `box ${asset.collision.width}x${asset.collision.height}px`
    : 'none declared (presentation-only)';
  const animation = asset.animation
    ? `frames ${asset.animation.startFrame}-${asset.animation.endFrame} at ${asset.animation.framesPerSecond} FPS; ${asset.animation.loop ? 'looping' : 'one-shot'}`
    : 'single-frame; no baked animation';
  const current = asset.source
    ? `owner source \`${asset.source.filePath}\``
    : asset.developmentFallback?.kind === 'asset'
      ? `semantic alias to \`${asset.developmentFallback.assetId}\``
      : `Phaser ${asset.developmentFallback?.shape ?? 'unknown'} primitive`;
  const fileName = production.targetFilePath.replaceAll('\\', '/').split('/').at(-1);
  const folder = production.targetFilePath.slice(0, -fileName.length);
  const runtimeDisplay = asset.runtimeDisplays.length > 0
    ? asset.runtimeDisplays
      .map(({ consumer, width, height, note }) => `${consumer}: ${format(width)}x${format(height)}px${note ? ` (${note})` : ''}`)
      .join('; ')
    : 'consumer-controlled; no single fixed gameplay size is declared';
  return [
    `### ${ordinal}. ${asset.intendedGameplayUse} (\`${asset.id}\`)`,
    '',
    `- Deliver: \`${fileName}\` in \`${folder}\`.`,
    `- Canvas/sheet: ${asset.expectedWidth}x${asset.expectedHeight}px; frame ${asset.frameWidth}x${asset.frameHeight}px; ${asset.frameCount} frame(s); ${animation}.`,
    `- Pose/orientation: ${production.orientation}; horizontal mirroring ${asset.mirroring === 'none' ? 'is not permitted' : 'is permitted'}.`,
    `- Origin/pivot: (${format(asset.origin.x)}, ${format(asset.origin.y)}); uniform authoring scale hint ${format(asset.worldScale)}; expected depth ${asset.expectedDepth}.`,
    `- Actual runtime display contract: ${runtimeDisplay}. Runtime display sizes take precedence over the authoring scale hint.`,
    `- Gameplay footprint: ${collision}. Attachments: ${asset.attachments.map((point) => `${point.name} (${format(point.x)}, ${format(point.y)})`).join(', ') || 'none'}.`,
    `- Alpha: ${production.transparency}. Usage: ${asset.intendedGameplayUse}.`,
    `- Current development representation: ${current}.`,
    `- Runtime presentation: ${production.runtimePresentation.join(' ')}`,
    ...(production.templateFilePath ? [`- Drawing guide: \`${production.templateFilePath}\`.`] : []),
    '',
  ];
}

function renderAudioEntry(audio, ordinal) {
  const fallback = audio.developmentFallback;
  const ambience = audio.category === 'ambience';
  const target = audio.productionTargetFilePath;
  const current = audio.source
    ? `owner source \`${audio.source.filePath}\`; procedural fallback remains available on playback failure`
    : `procedural ${fallback.oscillator} Web Audio ${fallback.generator} at ${fallback.frequencyHz}${fallback.endFrequencyHz ? `-${fallback.endFrequencyHz}` : ''} Hz`;
  const minimumDuration = Math.min(0.8, Math.max(0.05, fallback.durationSeconds ?? 0.25));
  const duration = ambience
    ? '90-180 seconds with a sample-accurate seamless loop'
    : minimumDuration === 0.8
      ? '0.80 seconds; leave a short natural decay'
      : `${minimumDuration.toFixed(2)}-0.80 seconds; leave a short natural decay`;
  return [
    `#### A${ordinal}. ${audio.intendedGameplayUse} (\`${audio.id}\`)`,
    '',
    `- Deliver: \`${target.split('/').at(-1)}\` in \`${target.slice(0, target.lastIndexOf('/') + 1)}\`.`,
    `- Format: 48 kHz, 24-bit PCM WAV, ${ambience ? 'stereo' : 'mono'}, ${duration}; ${audio.loop ? 'looping' : 'one-shot'}.`,
    '- Visual-only fields: dimensions, frames, orientation, pivot, and transparency are not applicable to audio.',
    `- Usage: ${audio.intendedGameplayUse}. Current representation: ${current}.`,
    '- Keep loudness conservative and audition through the existing master/music/effects volume controls.',
    '',
  ];
}

function format(value) {
  return Number(value).toFixed(2).replace(/0+$/, '').replace(/\.$/, '');
}
