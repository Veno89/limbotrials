import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createServer } from 'vite';

const outputPath = path.resolve('docs/ASSET_PRODUCTION_BACKLOG.md');
const checkOnly = process.argv.includes('--check');
const server = await createServer({ appType: 'custom', server: { middlewareMode: true } });

try {
  const { VISUAL_ASSETS, AUDIO_ASSET_MANIFEST } = await server.ssrLoadModule(
    '/src/game/data/assets.ts',
  );
  const { ASSET_CHECKLIST_CATEGORIES, ASSET_CREATIVE_CONCEPTS } = await server.ssrLoadModule(
    '/src/game/data/assetCreativeBriefs.ts',
  );

  const productionVisualAssets = VISUAL_ASSETS
    .filter((asset) => asset.production)
    .sort((left, right) => (
      left.production.order - right.production.order || left.id.localeCompare(right.id)
    ));
  const productionAssets = [...productionVisualAssets, ...AUDIO_ASSET_MANIFEST];
  validateCreativeConcepts({
    categories: ASSET_CHECKLIST_CATEGORIES,
    concepts: ASSET_CREATIVE_CONCEPTS,
    productionAssets,
  });

  const orderByAssetId = new Map(
    productionVisualAssets.map((asset, index) => [asset.id, index]),
  );
  for (const [index, asset] of AUDIO_ASSET_MANIFEST.entries()) {
    orderByAssetId.set(asset.id, productionVisualAssets.length + index);
  }
  const orderOf = (concept) => Math.min(
    ...concept.assetIds.map((assetId) => orderByAssetId.get(assetId)),
  );
  const orderedConcepts = [...ASSET_CREATIVE_CONCEPTS]
    .sort((left, right) => orderOf(left) - orderOf(right) || left.id.localeCompare(right.id));
  const startHere = orderedConcepts.filter((concept) => concept.startHere);

  const lines = [
    '# Asset Creation Checklist',
    '',
    '> Generated by `npm run assets:backlog`. Edit names and art direction in `src/game/data/assetCreativeBriefs.ts`; technical paths, dimensions, pivots, and runtime contracts remain in `src/game/data/assets.ts`.',
    '',
    'This is the artist-facing list: choose a name, make the thing, and send it back under that name. Some entries already have draft or reference art, so they can be reviewed or repainted instead of recreated blindly.',
    '',
    `The technical manifest contains **${productionVisualAssets.length} visual rows** and **${AUDIO_ASSET_MANIFEST.length} audio rows**. Related rows are condensed here into **${orderedConcepts.length} understandable creative concepts**.`,
    '',
    '## Shared visual direction',
    '',
    '- **World:** worn funerary grimdark—blackened or rusted iron, bone, cracked cathedral stone, ash, wax, tattered cloth, old leather, and restrained tarnished gold.',
    '- **Color language:** pale cyan means souls, player safety, or sacred relief; violet means the void; crimson and red-orange signal enemy danger; sickly green means poison.',
    '- **Avoid:** polished heroic fantasy, clean modern science fiction, cute or glossy styling, and decorative detail that weakens the silhouette.',
    '- **Readability:** build each image around one bold top-down silhouette. Do not paint in runtime glow, drop shadows, damage flashes, or danger rims—the game adds those effects.',
    '',
    '## Start here',
    '',
    'These five pieces give the demo its clearest immediate identity:',
    '',
    ...startHere.flatMap((concept, index) => [
      `${index + 1}. **${concept.displayName}** — ${concept.creativeBrief}`,
    ]),
    '',
    'They also appear in their normal categories below, so there is only one checklist to maintain.',
    '',
  ];

  for (const category of ASSET_CHECKLIST_CATEGORIES) {
    const concepts = orderedConcepts
      .filter((concept) => concept.category === category)
      .sort((left, right) => left.displayName.localeCompare(right.displayName));
    lines.push(`## ${category}`, '');
    for (const concept of concepts) {
      lines.push(`- [ ] **${concept.displayName}** — ${concept.creativeBrief}`);
    }
    lines.push('');
  }

  lines.push(
    '## When an asset is ready',
    '',
    'Send it back using the bold checklist name. The integrator will match it to the stable manifest entry, apply the exact canvas and runtime requirements, inspect it in the F11 Content Lab when applicable, and run the content and release checks. You do not need to work from file paths or technical IDs in this document.',
    '',
  );

  const generated = `${lines.join('\n')}\n`;
  if (checkOnly) {
    const current = await readFile(outputPath, 'utf8').catch(() => undefined);
    if (current !== generated) {
      throw new Error(
        `${path.relative(process.cwd(), outputPath)} is missing or stale. Run npm run assets:backlog.`,
      );
    }
    console.log(
      `${path.relative(process.cwd(), outputPath)} matches the manifest (${productionVisualAssets.length} visual + ${AUDIO_ASSET_MANIFEST.length} audio rows condensed into ${orderedConcepts.length} creative concepts).`,
    );
  } else {
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, generated, 'utf8');
    console.log(
      `Wrote ${path.relative(process.cwd(), outputPath)} (${productionVisualAssets.length} visual + ${AUDIO_ASSET_MANIFEST.length} audio rows condensed into ${orderedConcepts.length} creative concepts).`,
    );
  }
} finally {
  await server.close();
}

function validateCreativeConcepts({ categories, concepts, productionAssets }) {
  const categorySet = new Set(categories);
  const expectedAssetIds = new Set(productionAssets.map(({ id }) => id));
  const conceptIds = new Set();
  const assignedAssetIds = new Set();

  for (const concept of concepts) {
    if (!concept.id?.trim() || conceptIds.has(concept.id)) {
      throw new Error(`Creative concept IDs must be non-empty and unique: ${concept.id ?? '<missing>'}`);
    }
    conceptIds.add(concept.id);
    if (!concept.displayName?.trim() || !concept.creativeBrief?.trim()) {
      throw new Error(`Creative concept ${concept.id} needs a display name and design prompt.`);
    }
    if (!categorySet.has(concept.category)) {
      throw new Error(`Creative concept ${concept.id} has unknown category: ${concept.category}`);
    }
    if (!Array.isArray(concept.assetIds) || concept.assetIds.length === 0) {
      throw new Error(`Creative concept ${concept.id} must represent at least one manifest row.`);
    }
    for (const assetId of concept.assetIds) {
      if (!expectedAssetIds.has(assetId)) {
        throw new Error(`Creative concept ${concept.id} refers to unknown production asset: ${assetId}`);
      }
      if (assignedAssetIds.has(assetId)) {
        throw new Error(`Production asset ${assetId} appears in more than one creative concept.`);
      }
      assignedAssetIds.add(assetId);
    }
  }

  const missingAssetIds = [...expectedAssetIds].filter((assetId) => !assignedAssetIds.has(assetId));
  if (missingAssetIds.length > 0) {
    throw new Error(`Creative checklist is missing production assets: ${missingAssetIds.join(', ')}`);
  }
}
